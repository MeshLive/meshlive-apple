"""Convert Android's generated Bmh3Vectors.kt (tools/bmh3_reference.py output) into a Swift test fixture.

Usage: python bmh3_vectors_to_swift.py <Bmh3Vectors.kt> <Bmh3Vectors.swift>
Pure text transformation; the bytes are copied unchanged.
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()

consts = dict(re.findall(r'const val (\w+) = "([0-9a-f]*)"', src))
blocks = ["\n" + b for b in re.split(r'\n        Vector\(\n', src)[1:]]


def pairs(text):
    return re.findall(r'"([A-Za-z0-9_]+)" to "([^"]*)"', text)


def field_map(block, name):
    m = re.search(r'\n            ' + name + r' = mapOf\((.*?)\),\n', block, re.S)
    return pairs(m.group(1)) if m else []


def scalar(block, name):
    return re.search(r'\n            ' + name + r' = "([^"]*)"', block).group(1)


def swift_map(items, indent):
    if not items:
        return "[:]"
    pad = " " * indent
    body = ",\n".join(f'{pad}    "{k}": "{v}"' for k, v in items)
    return "[\n" + body + f",\n{pad}]"


out = [
    "// GENERATED from the Android repository's app/src/test/.../Bmh3Vectors.kt (itself generated by",
    "// tools/bmh3_reference.py) by Interop/bmh3_vectors_to_swift.py. Do not edit by hand.",
    "",
    "enum Bmh3Vectors {",
]
for k, v in consts.items():
    out.append(f'    static let {k.lower() if False else k}: String = "{v}"')
out += [
    "",
    "    struct Vector {",
    "        let name: String, purpose: String, order: String",
    "        let inputs: [String: String], messages: [String: String], trace: [String: String]",
    "        let bms1FirstRecordI2r: String, bms1FirstRecordR2i: String",
    "        let reveal: [String: String]",
    "    }",
    "",
    "    static let all: [Vector] = [",
]
for block in blocks:
    out.append("        Vector(")
    out.append(f'            name: "{scalar(block, "name")}", purpose: "{scalar(block, "purpose")}", order: "{scalar(block, "order")}",')
    for field in ("inputs", "messages", "trace"):
        out.append(f"            {field}: {swift_map(field_map(block, field), 12)},")
    out.append(f'            bms1FirstRecordI2r: "{scalar(block, "bms1FirstRecordI2r")}",')
    out.append(f'            bms1FirstRecordR2i: "{scalar(block, "bms1FirstRecordR2i")}",')
    out.append(f"            reveal: {swift_map(field_map(block, 'reveal'), 12)}")
    out.append("        ),")
out += ["    ]", "}", ""]
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(len(blocks), "vectors")
