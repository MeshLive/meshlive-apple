#!/usr/bin/env python3
"""Generate App/UI/DesignTokens.swift from Design/design-tokens.json (copied from Android's tokens).
--check exits 1 when the Swift file is out of date."""
import json, sys
from pathlib import Path
root = Path(__file__).resolve().parent.parent
tokens = json.loads((root / "Design/design-tokens.json").read_text(encoding="utf-8"))

def argb(hexstr):
    h = hexstr.lstrip("#")
    if len(h) == 6: h = "FF" + h
    return "0x" + h.upper()

lines = ["// Generated by Scripts/tokens.py from Design/design-tokens.json (Android \"Field radio\" tokens). Do not edit.",
         "import SwiftUI", "", "enum DesignTokens {", "    enum Colors {"]
for name, c in tokens["colors"].items():
    lines.append(f"        /// Android `{c['android']}`")
    lines.append(f"        static let {name} = TokenColor(dark: {argb(c['dark'])}, light: {argb(c['light'])})")
lines += ["    }", "    enum Dimens {"]
for name, v in tokens["dimens"].items():
    lines.append(f"        static let {name}: CGFloat = {v}")
lines += ["    }", "    enum TypeScale {"]
for name, t in tokens["type"].items():
    weight = {"bold": ".bold", "medium": ".medium", "regular": ".regular"}[t["weight"]]
    lines.append(f"        /// Android `{t['android']}`")
    lines.append(f"        static let {name} = TokenType(size: {t['size']}, weight: {weight}, condensed: {str(t['condensed']).lower()}, tabular: {str(t.get('tabular', False)).lower()})")
lines += ["    }", "}", ""]
out = "\n".join(lines)
target = root / "App/UI/DesignTokens.swift"
if "--check" in sys.argv:
    current = target.read_text(encoding="utf-8") if target.exists() else ""
    if current != out: print("App/UI/DesignTokens.swift is out of date: run python3 Scripts/tokens.py"); sys.exit(1)
    print("Design tokens up to date"); sys.exit(0)
target.write_text(out, encoding="utf-8", newline="\n")
print(f"Wrote {target.relative_to(root)} ({len(tokens['colors'])} colours, {len(tokens['type'])} type styles, {len(tokens['dimens'])} dimens)")
